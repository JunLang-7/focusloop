#!/usr/bin/env node
/**
 * Release hygiene gate.
 *
 * The repository must not ship temporary AI scaffolding, scratch notes, debug
 * leftovers or unexplained TODOs. It must NOT remove third-party licences,
 * legitimate attribution or real provenance — so this script only looks for
 * artefacts that were never meant to be committed.
 *
 * Exit code 1 means the repository is not releasable.
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

const SKIP_DIRECTORIES = new Set([
  '.git',
  'node_modules',
  '.nx',
  '.nx-cache',
  'dist',
  'build',
  'out',
  'release',
  'coverage',
  'test-results',
  'playwright-report',
  'tmp',
  '.angular',
  '.vscode-test',
]);

const TEXT_EXTENSIONS = new Set([
  '.ts',
  '.js',
  '.mjs',
  '.cjs',
  '.json',
  '.md',
  '.txt',
  '.yml',
  '.yaml',
  '.html',
  '.css',
  '.scss',
  '.mts',
  '.cts',
  '.jsonc',
]);

const SKIP_FILES = new Set(['pnpm-lock.yaml', 'package-lock.json', 'verify-no-scaffolding.mjs']);

/** Patterns that must never appear in a committed file. */
const FORBIDDEN = [
  { name: 'AI provenance claim', pattern: /\bgenerated by (claude|ai|copilot|gpt|chatgpt)\b/i },
  { name: 'AI provenance claim', pattern: /\bas an ai\b/i },
  { name: 'AI provenance claim', pattern: /\bai-generated\b/i },
  { name: 'AI provenance claim', pattern: /\bthis (file|code) was written by an? (ai|model)\b/i },
  { name: 'placeholder content', pattern: /\blorem ipsum\b/i },
  { name: 'debug leftover', pattern: /\bconsole\.log\s*\(/ },
  { name: 'debug leftover', pattern: /\bdebugger\s*;/ },
];

/**
 * `placeholder` is legitimate as an attribute or a YAML field name, so it is only
 * flagged when it is being used as a description of content.
 */
const PLACEHOLDER_AS_FIELD = /placeholder\s*[:=]/;

const CODE_EXTENSIONS = new Set(['.ts', '.js', '.mjs', '.cjs', '.mts', '.cts', '.html', '.css']);

const UNEXPLAINED_TODO = /\b(TODO|FIXME)\b(?!\s*\(#\d+\))/;

function isTextFile(name) {
  const dot = name.lastIndexOf('.');
  if (dot < 0) return false;
  return TEXT_EXTENSIONS.has(name.slice(dot).toLowerCase());
}

function isCodeFile(name) {
  const dot = name.lastIndexOf('.');
  if (dot < 0) return false;
  return CODE_EXTENSIONS.has(name.slice(dot).toLowerCase());
}

const findings = [];

function scanFile(absolutePath) {
  const name = absolutePath.split(sep).pop() ?? '';
  if (SKIP_FILES.has(name)) return;

  let content;
  try {
    content = readFileSync(absolutePath, 'utf8');
  } catch {
    return;
  }

  const relativePath = relative(root, absolutePath).split(sep).join('/');
  const codeFile = isCodeFile(name);
  const lines = content.split('\n');

  lines.forEach((line, index) => {
    const lineNumber = index + 1;

    // Patterns are only matched outside inline code spans and quoted strings, so
    // documentation that *describes* a forbidden pattern is not a false positive.
    const searchable = line
      .replace(/`[^`]*`/g, '``')
      .replace(/"[^"]*"/g, '""')
      .replace(/'[^']*'/g, "''");

    for (const { name: label, pattern } of FORBIDDEN) {
      if (pattern.test(searchable)) {
        findings.push({ file: relativePath, line: lineNumber, label, text: line.trim() });
      }
    }

    if (!PLACEHOLDER_AS_FIELD.test(searchable) && /\bplaceholder\b/i.test(searchable)) {
      findings.push({
        file: relativePath,
        line: lineNumber,
        label: 'placeholder content',
        text: line.trim(),
      });
    }

    // Only code can carry an actionable TODO; prose that discusses the rule cannot.
    if (codeFile && UNEXPLAINED_TODO.test(searchable)) {
      findings.push({
        file: relativePath,
        line: lineNumber,
        label: 'unexplained TODO/FIXME (use "TODO (#123):")',
        text: line.trim(),
      });
    }
  });
}

function walk(directory) {
  for (const entry of readdirSync(directory)) {
    if (SKIP_DIRECTORIES.has(entry)) continue;
    const absolute = join(directory, entry);
    let stats;
    try {
      stats = statSync(absolute);
    } catch {
      continue;
    }
    if (stats.isDirectory()) {
      walk(absolute);
    } else if (stats.isFile() && isTextFile(entry)) {
      scanFile(absolute);
    }
  }
}

walk(root);

if (findings.length === 0) {
  console.log('Release hygiene: clean.');
  process.exit(0);
}

console.error(`Release hygiene: ${findings.length} problem(s) found.\n`);
for (const finding of findings) {
  console.error(`  ${finding.file}:${finding.line}  [${finding.label}]`);
  console.error(`      ${finding.text.slice(0, 120)}`);
}
console.error('\nFix or remove these before releasing.');
process.exit(1);
